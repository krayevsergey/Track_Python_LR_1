salary = 5000  # Ежемесячная зарплата
spend = 6000  # Траты за первый месяц
months = 10  # Количество месяцев, которое планируется протянуть без долгов
increase = 0.03  # Ежемесячный рост цен

# TODO Рассчитайте подушку безопасности, чтобы протянуть 10 месяцев без долгов

money_capital = 0  # Подушка безопасности, которую будем рассчитывать

# Копируем расходы первого месяца
current_spend = spend

# Цикл for для прохода по месяцам
for month in range(months):
    # Определяем разницу между тратами и зарплатой
    difference = current_spend - salary

    # Если разница положительная, нужна подушка безопасности
    if difference > 0:
        money_capital += difference

    # Увеличиваем траты на следующий месяц (кроме первого месяца)
    current_spend *= (1 + increase)

# Округляем результат до целого
money_capital = round(money_capital)

print(f"Подушка безопасности, чтобы протянуть {months} месяцев без долгов:", money_capital)

